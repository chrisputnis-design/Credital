"""Generate preflop_table.py: equity of each of the 169 starting-hand classes vs a random hand.

    python -m pokerbot.gen_preflop [samples_per_hand]
"""
from __future__ import annotations

import random
import sys

from .cards import RANKS
from .evaluator import evaluate


def main(n: int = 6000):
    rng = random.Random(12345)
    table = {}
    for hi in range(12, -1, -1):
        for lo in range(hi, -1, -1):
            for suited in ((False,) if hi == lo else (True, False)):
                c1 = hi * 4
                c2 = lo * 4 + (0 if suited else 1)
                if c1 == c2:
                    c2 = lo * 4 + 1
                rest = [c for c in range(52) if c != c1 and c != c2]
                wins = 0.0
                for _ in range(n):
                    x = rng.sample(rest, 7)
                    board = x[2:]
                    a = evaluate((c1, c2) + tuple(board))
                    b = evaluate((x[0], x[1]) + tuple(board))
                    wins += 1.0 if a > b else (0.5 if a == b else 0.0)
                key = RANKS[hi] + RANKS[lo] + ("" if hi == lo else ("s" if suited else "o"))
                table[key] = round(wins / n, 4)
    with open(__file__.replace("gen_preflop.py", "preflop_table.py"), "w") as f:
        f.write('"""Generated by gen_preflop.py: equity vs a random hand, keyed by hand class."""\n')
        f.write("PREFLOP_EQUITY = {\n")
        for k, v in table.items():
            f.write(f'    "{k}": {v},\n')
        f.write("}\n")
    print(f"wrote {len(table)} hand classes")


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 6000)
